const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '..')
const home = fs.readFileSync(path.join(root, 'home.html'), 'utf8')
const hub = fs.readFileSync(path.join(root, 'patient-care-hub.html'), 'utf8')

const unique = (items) => Array.from(new Set(items.filter(Boolean)))
const routePattern = /(?:window\.location(?:\.href|\.replace)\s*(?:=|\()\s*|AppNavigation\.open\(\s*)['"`]([^'"`?]+\.html)/g
const routeTargets = (source) => {
  const routes = []
  let match
  while ((match = routePattern.exec(source))) routes.push(`/${match[1]}`)
  return routes
}

const htmlRoutes = fs.readdirSync(root)
  .filter((name) => name.endsWith('.html'))
  .map((name) => `/${name}`)

const coreRoutes = [
  '/index.html',
  '/login.html',
  '/home.html',
  '/list.html',
  '/patient-enhanced.html',
  '/patient-consent.html',
  '/antenatal-form.html',
  '/offline.html'
]

const staticAssets = []
const collectStaticAssets = (directory, prefix) => {
  for (const name of fs.readdirSync(directory)) {
    const absolute = path.join(directory, name)
    const relative = path.join(prefix, name)
    const stats = fs.statSync(absolute)
    if (stats.isDirectory()) {
      collectStaticAssets(absolute, relative)
      continue
    }
    if (/\.(?:js|css|png|jpe?g|gif|svg|webp|ico|woff2?|ttf|eot)$/i.test(name)) {
      staticAssets.push(`/${relative.split(path.sep).join('/')}`)
    }
  }
}
collectStaticAssets(path.join(root, 'js'), 'js')
collectStaticAssets(path.join(root, 'css'), 'css')

const manifest = {
  coreRoutes,
  homeRoutes: unique(routeTargets(home)),
  clinicalRoutes: unique(routeTargets(hub)),
  htmlRoutes: unique(htmlRoutes),
  staticAssets: unique(staticAssets)
}

const output = `/* Generated by scripts/generate-pwa-manifest.js. Do not edit manually. */
self.MNCH_PWA_MANIFEST = ${JSON.stringify(manifest, null, 2)}
`

fs.writeFileSync(path.join(root, 'js/pwa-route-manifest.js'), output)
console.log(`Generated ${manifest.htmlRoutes.length} routes and ${manifest.staticAssets.length} static assets`)
